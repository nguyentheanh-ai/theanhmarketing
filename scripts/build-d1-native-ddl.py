"""Translate captured Supabase schema into faithful D1 (SQLite) DDL.

Output: scripts/generated/d1-native-<a|b>.sql and a report of every Postgres
rule that could not be translated (enforced in the shim or listed as a gap).
Table names follow copy-supabase-to-d1.py: <project>_<schema>__<table>.
"""
import json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
AFF = {'int2': 'INTEGER', 'int4': 'INTEGER', 'int8': 'INTEGER', 'bool': 'INTEGER', 'float4': 'REAL', 'float8': 'REAL'}

class Untranslatable(Exception): pass

def split_top(s, sep=','):
    out, depth, cur, q = [], 0, '', False
    for ch in s:
        if ch == "'": q = not q
        if not q:
            if ch == '(' or ch == '[': depth += 1
            elif ch == ')' or ch == ']': depth -= 1
            elif ch == sep and depth == 0: out.append(cur); cur = ''; continue
        cur += ch
    out.append(cur); return [x.strip() for x in out]

def pg_expr(e, key, schema, table):
    """Best-effort Postgres boolean expression -> SQLite; raises Untranslatable."""
    # Anchored character-class regexes used by these schemas -> GLOB/length.
    def rx(m):
        col, pat = m.group(1), m.group(2)
        simple = re.fullmatch(r"\^([A-Za-z_]*)\[([^\]]+)\](\{(\d+)(,(\d+))?\}|\+)?\$", pat)
        if not simple: raise Untranslatable(pat)
        prefix, cls, q, lo, _, hi = simple.groups(); n = len(prefix)
        body = f"substr({col},{n+1})"
        if q is None: lo = hi = '1'
        elif q == '+': lo, hi = '1', None
        elif hi is None: hi = lo
        cond = [f"{body} NOT GLOB '*[^{cls}]*'", f"length({body})>={lo}"] + ([f"length({body})<={hi}"] if hi else [])
        if prefix: cond.insert(0, f"substr({col},1,{n})='{prefix}'")
        return '(' + ' AND '.join(cond) + ')'
    e = re.sub(r"(\w+) ~ '([^']+)'(::text)?", rx, e)
    if re.search(r"\s~\*?\s|::interval|interval|now\(\)|\bjsonb_array_length|\bcurrent_|\bdouble precision|\bstarts_at \+", e): raise Untranslatable(e)
    def any_array(m):
        items = split_top(m.group(2))
        return f"{m.group(1)} IN ({', '.join(items)})"
    e = re.sub(r"::\"?[a-z_ ]+\"?(\[\])?", '', e)
    for _ in range(3):
        e = re.sub(r"([\w.]+|\([\w.]+\))\s*=\s*ANY\s*\(ARRAY\[(.*?)\]\)", any_array, e)
    if 'ANY' in e or 'ARRAY' in e: raise Untranslatable(e)
    e = re.sub(r"\bTRIM\(BOTH FROM ([^)]+)\)", r"trim(\1)", e)
    e = re.sub(r"\bbtrim\(", "trim(", e); e = re.sub(r"\bchar_length\(", "length(", e)
    e = re.sub(r"\bjsonb_typeof\(", "json_type(", e)
    return e

def ddl(key):
    d = json.loads((ROOT / f'reports/cloudflare-d1/supabase-schema-{key}.json').read_text())
    tables, gaps, out = {}, [], [f"-- Generated by scripts/build-d1-native-ddl.py from supabase-schema-{key}.json. Candidate only.", "PRAGMA defer_foreign_keys = on;"]
    for c in d['columns']: tables.setdefault((c['schema'], c['table']), []).append(c)
    pks = {}; uniques = []; fks = {}; checks = {}
    for i in d['indexes']:
        if i['primary']:
            m = re.search(r"USING btree \(([^)]*)\)", i['def']); pks[(i['schema'], i['table'])] = [x.strip().strip('"') for x in m.group(1).split(',')]
        elif i['unique']: uniques.append(i)
    for c in d['constraints']:
        if c['type'] == 'f': fks.setdefault((c['schema'], c['table']), []).append(c)
        if c['type'] == 'c': checks.setdefault((c['schema'], c['table']), []).append(c)
    name = lambda s, t: f'"{key}_{s}__{t}"'
    for (s, t), cols in sorted(tables.items()):
        lines = []
        for c in sorted(cols, key=lambda c: c['position']):
            aff = AFF.get(c['udt'], 'TEXT'); nn = '' if c['nullable'] else ' NOT NULL'
            lines.append(f'"{c["column"]}" {aff}{nn}')
        if (s, t) in pks: lines.append('PRIMARY KEY(' + ', '.join(f'"{x}"' for x in pks[(s, t)]) + ')')
        for f in fks.get((s, t), []):
            m = re.match(r"FOREIGN KEY \(([^)]*)\) REFERENCES ([\w.]+)\(([^)]*)\)(.*)", f['def'])
            ref = m.group(2); rs, rt = ref.split('.') if '.' in ref else ('public', ref)
            if (rs, rt) not in tables: gaps.append({'kind': 'fk_external', 'table': f'{s}.{t}', 'def': f['def']}); continue
            od = re.search(r'ON DELETE (CASCADE|SET NULL|RESTRICT|SET DEFAULT)', m.group(4))
            lines.append(f"FOREIGN KEY({m.group(1)}) REFERENCES {name(rs, rt)}({m.group(3)})" + (f" ON DELETE {od.group(1)}" if od else '') + ' DEFERRABLE INITIALLY DEFERRED')
        for c in checks.get((s, t), []):
            body = re.match(r"CHECK \((.*)\)( NOT VALID)?$", c['def'], re.S)
            try:
                if body.group(2): raise Untranslatable('NOT VALID')
                lines.append(f"CHECK({pg_expr(body.group(1), key, s, t)})")
            except Untranslatable:
                gaps.append({'kind': 'check', 'table': f'{s}.{t}', 'name': c['name'], 'def': c['def']})
        out.append(f"CREATE TABLE IF NOT EXISTS {name(s, t)} (\n " + ',\n '.join(lines) + "\n);")
    for i in uniques:
        m = re.match(r"CREATE UNIQUE INDEX (\S+) ON (\w+)\.(\w+) USING btree \((.*?)\)( WHERE (.*))?$", i['def'])
        if not m: gaps.append({'kind': 'unique', 'def': i['def']}); continue
        try:
            cols = ', '.join(pg_expr(x, key, m.group(2), m.group(3)) for x in split_top(m.group(4)))
            where = f" WHERE {pg_expr(m.group(6), key, m.group(2), m.group(3))}" if m.group(6) else ''
            out.append(f'CREATE UNIQUE INDEX IF NOT EXISTS "{key}_{m.group(2)}__{m.group(1)}" ON {name(m.group(2), m.group(3))}({cols}){where};')
        except Untranslatable:
            gaps.append({'kind': 'unique', 'def': i['def']})
    for i in d['indexes']:
        if i['unique'] or i['primary']: continue
        m = re.match(r"CREATE INDEX (\S+) ON (\w+)\.(\w+) USING btree \(([^()]*?)\)( WHERE (.*))?$", i['def'])
        if not m: continue
        cols = ', '.join(re.sub(r'\s+(DESC|ASC)$', r' \1', x).replace('"', '') for x in split_top(m.group(4)))
        try:
            where = f" WHERE {pg_expr(m.group(6), key, m.group(2), m.group(3))}" if m.group(6) else ''
        except Untranslatable: where = None
        if where is not None: out.append(f'CREATE INDEX IF NOT EXISTS "{key}_{m.group(2)}__{m.group(1)}" ON {name(m.group(2), m.group(3))}({cols}){where};')
    gen = ROOT / 'scripts/generated'; gen.mkdir(exist_ok=True)
    (gen / f'd1-native-{key}.sql').write_text('\n'.join(out) + '\n')
    (ROOT / f'reports/cloudflare-d1/d1-native-ddl-gaps-{key}.json').write_text(json.dumps(gaps, ensure_ascii=False, indent=1) + '\n')
    print(key, len(tables), 'tables;', len(gaps), 'untranslated rules', {k: sum(1 for g in gaps if g['kind'] == k) for k in {g['kind'] for g in gaps}})

for k in (sys.argv[1:] or ['a', 'b']): ddl(k)
